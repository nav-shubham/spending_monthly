def clean_merchant_upi_string(upi_str: str) -> str:
    """Helper to clean a UPI ID string and extract name-like parts."""
    if not upi_str:
        return ""
    # Strip the @upi part
    parts = upi_str.split('@')
    name_part = parts[0]
    
    # Replace dots, hyphens, underscores with spaces
    cleaned = re.sub(r'[\.\-_]', ' ', name_part)
    # Remove numbers
    cleaned = re.sub(r'\d+', '', cleaned)
    # Strip double spaces
    cleaned = re.sub(r'\s+', ' ', cleaned).strip()
    # Title case
    return cleaned.title()

def get_ai_suggestion(upi_id: str, default_vendor: str, details_str: str, api_key: str = None) -> Dict[str, Any]:
    """
    Generates a suggested merchant name, confidence score, and explanation.
    Uses Gemini API if key is provided, otherwise falls back to local heuristics.
    """
    upi_clean = str(upi_id).strip().lower()
    vendor_clean = str(default_vendor).strip().lower()
    details_clean = str(details_str).strip().lower()
    
    # 1. Try Gemini API if available
    if api_key:
        try:
            url = f"https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash:generateContent?key={api_key}"
            prompt = f"""
            Identify the canonical/clean merchant name from the following UPI transaction details:
            - UPI ID: "{upi_id}"
            - Default Vendor Name: "{default_vendor}"
            - Transaction Details: "{details_str}"

            Respond ONLY with a JSON object in this exact format (no markdown formatting, no backticks):
            {{
                "suggested_merchant": "Clean Merchant Name (e.g. Swiggy, Blinkit, DMart, John Doe for P2P)",
                "confidence_score": 0.95,
                "reason": "Brief explanation of why this was chosen (e.g., Recognized brand keyword in UPI ID)"
            }}
            """
            
            headers = {"Content-Type": "application/json"}
            payload = {
                "contents": [{"parts": [{"text": prompt}]}],
                "generationConfig": {
                    "responseMimeType": "application/json"
                }
            }
            
            response = requests.post(url, json=payload, headers=headers, timeout=5)
            if response.status_code == 200:
                res_data = response.json()
                text_content = res_data['candidates'][0]['content']['parts'][0]['text']
                # Parse JSON output
                suggestion = json.loads(text_content.strip())
                if "suggested_merchant" in suggestion and "confidence_score" in suggestion:
                    return {
                        "suggested_merchant": suggestion["suggested_merchant"],
                        "confidence_score": float(suggestion["confidence_score"]),
                        "reason": suggestion.get("reason", "Generated by Gemini API.")
                    }
        except Exception as e:
            # Fall back to heuristics silently on error
            print(f"Gemini API suggestion failed: {e}")

    # 2. Local Heuristic/Regex engine (Fallback)
    # Check well-known merchant patterns
    for pattern, clean_name in WELL_KNOWN_MERCHANTS.items():
        if re.search(pattern, upi_clean) or re.search(pattern, vendor_clean) or re.search(pattern, details_clean):
            return {
                "suggested_merchant": clean_name,
                "confidence_score": 0.90,
                "reason": f"Recognized brand '{clean_name}' in UPI ID or details."
            }

    # Check for P2P (individual) transfer (numbers at start of UPI ID usually indicates phone number)
    if re.match(r'^\+?\d{10,12}$', upi_clean.split('@')[0]):
        return {
            "suggested_merchant": default_vendor if default_vendor not in ("Unknown", "Other") else "Peer-to-Peer Transfer",
            "confidence_score": 0.85,
            "reason": "UPI ID format matches a phone number (Peer-to-Peer payment)."
        }

    # If UPI ID has some word characters, try to clean it
    upi_name = clean_merchant_upi_string(upi_id)
    if upi_name and len(upi_name) > 3 and upi_name.lower() not in ("unknown", "other"):
        return {
            "suggested_merchant": upi_name,
            "confidence_score": 0.70,
            "reason": f"Extracted merchant name from UPI ID string '{upi_id}'."
        }

    # Fallback to default cleaned vendor
    if default_vendor and default_vendor not in ("Unknown", "Other"):
        return {
            "suggested_merchant": default_vendor,
            "confidence_score": 0.50,
            "reason": "Default cleaned description value used as best guess."
        }

    return {
        "suggested_merchant": "Unknown Merchant",
        "confidence_score": 0.10,
        "reason": "Unable to determine merchant from available information."
    }
